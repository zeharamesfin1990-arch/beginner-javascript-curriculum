// Comparison operators compare values and return true or false
console.log(5 > 3);    // Greater than
console.log(5 < 3);    // Less than
console.log(5 >= 5);   // Greater than or equal to
console.log(4 <= 4);   // Less than or equal to
console.log(5 == "5"); // Equal to
console.log(3 != 3); // Not equal to
console.log(5 === "5"); // Strictly equal to
console.log(5 !== 3);   // Strictly not equal to

// You can compare variables too
let a = 10;
let b = 7;
console.log(a > b);
console.log(a === b);

console.log("apple" === "apple");
console.log("Apple" === "apple");  // Case matters when comparing strings
console.log("apple" !== "banana");
console.log("cat" > "bat");  // Comparisons with strings are done alphabetically
console.log("dog" < "zebra");
